"""Generate ``BENCHMARKS_HEAD_TO_HEAD.md`` from ``head_to_head_summary.json``
(SPEC v4 DoD-9, D17, D24, D28, D48, D57, D61).

Pure transform: summary JSON in → markdown out. No side-effects aside from
the output file write. Byte-identical regeneration from the same input is
required so CI's regenerate-and-diff check (D28) can enforce generator-only
edits.

Determinism
-----------
- All float formatting uses ``f"{x:.4f}"`` (D45).
- Dicts are iterated in sorted-key order.
- No wall-clock reads; ``run_date`` + ``agentarmor_version`` come from the
  summary JSON.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

from .schema_io import load_summary
from .taxonomy_applicability import APPLIES


GENERATED_MARKER = (
    "<!-- GENERATED by benchmarks/generate_head_to_head_doc.py "
    "— edits here will be overwritten. "
    "Change the generator and regenerate. -->"
)


def _fmt(value: Optional[float]) -> str:
    if value is None:
        return "—"
    return f"{value:.4f}"


def _fmt_latency(value: Optional[float]) -> str:
    if value is None:
        return "—"
    return f"{value:.1f} ms"


def _fmt_ci(point: Optional[float], lo: Optional[float], hi: Optional[float]) -> str:
    if point is None:
        return "—"
    if lo is None or hi is None:
        return f"{point:.4f}"
    return f"{point:.4f} (CI {lo:.4f}–{hi:.4f})"


def _cells_by_dataset(cells: List[Dict[str, Any]]) -> Dict[str, List[Dict[str, Any]]]:
    by_dataset: Dict[str, List[Dict[str, Any]]] = {}
    for cell in cells:
        by_dataset.setdefault(cell["dataset"], []).append(cell)
    for d in by_dataset:
        by_dataset[d] = sorted(by_dataset[d], key=lambda c: c["baseline"])
    return by_dataset


def _headline_block() -> str:
    return (
        "This document compares AgentArmor against two established safety classifiers — "
        "LlamaGuard 3 (local, Q4_K_M via llama-cpp-python) and OpenAI Moderation "
        "(omni-moderation-latest) — across six industry datasets with per-sample verdicts "
        "and bootstrap confidence intervals. Perspective API was considered but excluded "
        "from v1: Google/Jigsaw announced sunset with API EOL 2026-12-31, which would "
        "leave any published comparison non-reproducible within months. We publish "
        "per-dataset numbers only: no overall-winner claim, and we annotate every cell "
        "where AgentArmor loses or ties within CI. Reproduction: set `OPENAI_API_KEY` and "
        "run `python -m benchmarks.run_head_to_head --run-dir benchmarks/results/runs/<ts>` "
        "(see [`RUNBOOK.md`](RUNBOOK.md) Procedure 0)."
    )


def _operating_point_legend(cells: List[Dict[str, Any]]) -> str:
    lines = [
        "### Operating-point legend",
        "",
        "| Baseline | Operating point |",
        "| --- | --- |",
    ]
    seen = set()
    # Deterministic order by baseline.
    for baseline in sorted({c["baseline"] for c in cells}):
        if baseline in seen:
            continue
        seen.add(baseline)
        op = _legend_for(baseline)
        lines.append(f"| `{baseline}` | {op} |")
    return "\n".join(lines)


def _legend_for(baseline: str) -> str:
    return {
        "llamaguard": 'P("unsafe") from Q4_K_M first-token logprobs (our quantization choice)',
        "openai_moderation": "max over per-dataset category projection (see rubric)",
        "perspective": "TOXICITY ≥ 0.5 (our threshold — Perspective ships none)",
        "mock_scored": "scripted scores (CI fixture only)",
    }.get(baseline, "—")


def _delta_strip(cells: List[Dict[str, Any]]) -> str:
    """Per-dataset strip: best-baseline F1 per row (AgentArmor column reserved)."""
    by = _cells_by_dataset(cells)
    lines = [
        "### Per-dataset summary",
        "",
        "| Dataset | Best baseline F1 | Best baseline | AgentArmor F1 | Δ vs best |",
        "| --- | --- | --- | --- | --- |",
    ]
    for dataset in sorted(by):
        baseline_cells = [c for c in by[dataset] if c["baseline"] != "mock_scored"]
        baseline_cells = [c for c in baseline_cells if c.get("f1") is not None]
        agentarmor_cells = [
            c for c in by[dataset] if c.get("baseline", "").startswith("agentarmor_")
        ]
        if not baseline_cells:
            lines.append(f"| `{dataset}` | — | — | — | — |")
            continue
        best = max(baseline_cells, key=lambda c: c["f1"])
        best_f1 = best["f1"]
        best_name = best["baseline"]
        agentarmor_f1 = (
            agentarmor_cells[0]["f1"] if agentarmor_cells and agentarmor_cells[0].get("f1") is not None else None
        )
        delta = (
            (agentarmor_f1 - best_f1) if (agentarmor_f1 is not None) else None
        )
        lines.append(
            f"| `{dataset}` | {_fmt(best_f1)} | `{best_name}` | {_fmt(agentarmor_f1)} | {_fmt(delta)} |"
        )
    return "\n".join(lines)


def _per_dataset_tables(cells: List[Dict[str, Any]]) -> str:
    by = _cells_by_dataset(cells)
    sections: List[str] = []
    for dataset in sorted(by):
        sections.append(f"### {dataset}\n")
        sections.append(
            "| Baseline | F1 | Precision | Recall | FPR | MCC | Bal-Acc | Latency p50 | Latency p95 | N | Errors |"
        )
        sections.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
        for cell in by[dataset]:
            row = (
                f"| `{cell['baseline']}` "
                f"| {_fmt_ci(cell.get('f1'), cell.get('f1_ci_low'), cell.get('f1_ci_high'))} "
                f"| {_fmt(cell.get('precision'))} "
                f"| {_fmt(cell.get('recall'))} "
                f"| {_fmt(cell.get('fpr'))} "
                f"| {_fmt_ci(cell.get('mcc'), cell.get('mcc_ci_low'), cell.get('mcc_ci_high'))} "
                f"| {_fmt_ci(cell.get('balanced_accuracy'), cell.get('balanced_accuracy_ci_low'), cell.get('balanced_accuracy_ci_high'))} "
                f"| {_fmt_latency(cell.get('latency_p50_ms'))} "
                f"| {_fmt_latency(cell.get('latency_p95_ms'))} "
                f"| {cell.get('n_samples', 0)} "
                f"| {cell.get('errors_count', 0)} |"
            )
            sections.append(row)
        # Highlight if AdvBench-style omission applies (per D38, F1 not meaningful).
        if dataset == "advbench":
            sections.append(
                "\n_AdvBench is reported with MCC + balanced-accuracy only; F1 omitted "
                "due to the 520:15 imbalance baseline-rate dominating F1 (SPEC v4 D38)._"
            )
        sections.append("")  # blank line between sections
    return "\n".join(sections).rstrip() + "\n"


def _does_not_apply_appendix() -> str:
    lines = [
        "### Cells marked `does_not_apply`",
        "",
        "The applicability rubric (`benchmarks/taxonomy_applicability.py`) declares a "
        "(baseline, dataset) pair inapplicable when the baseline's taxonomy does not "
        "meaningfully overlap the dataset's labeling construct. Those cells are omitted "
        "from the comparison tables above.",
        "",
        "| Baseline | Dataset | Rationale |",
        "| --- | --- | --- |",
    ]
    entries = sorted(APPLIES.items(), key=lambda kv: (kv[0][0], kv[0][1]))
    for (baseline, dataset), entry in entries:
        if entry.verdict != "does_not_apply":
            continue
        lines.append(f"| `{baseline}` | `{dataset}` | {entry.rationale} |")
    return "\n".join(lines)


def _pr_curves_appendix() -> str:
    return (
        "### PR curves (appendix)\n\n"
        "Precision–recall curves are rendered only for score-emitting `(baseline, dataset)` "
        "pairs on the six main-comparison datasets, and only when at least 50 positive samples "
        "are present (below that, bootstrap PR is too noisy to publish honestly — SPEC v4 D12).\n\n"
        "**Why a PR curve is missing (D48):**\n\n"
        "- `shield` (regex; bool-by-design, no curve)\n"
        "- `exfiltration_guard` (regex; bool-by-design, no curve)\n"
        "- `unicode_shield` (regex; bool-by-design, no curve)\n"
        "- `llamaguard` (when the logprobs gate fell back to text-parse — cell "
        "scores 0/1 only; see D36 and TYPE_WALKTHROUGH.md V1)\n"
        "- Cells with fewer than 50 positives (noise floor)\n\n"
        "_Curves are not yet rendered in this preview; the schema retains the per-sample "
        "`pred_score` needed to generate them from `head_to_head_verdicts.jsonl`._"
    )


def _methodology_footer() -> str:
    return (
        "### Methodology notes\n\n"
        "- **Bootstrap F1 CI:** 5000 iterations, per-cell seed derived from "
        "`sha256(baseline|dataset)` (SPEC v4 D44/D45). `random.Random`, not numpy — "
        "survives minor-version bumps across the pinned `numpy<2.0`.\n"
        "- **Per-metric degenerate guards (D41):** F1, MCC, and balanced-accuracy each "
        "have distinct zero-denominator conditions; cells flagged \"insufficient data "
        "for CI\" (`degenerate_flag=true`) report the point estimate alone.\n"
        "- **Reproducibility tolerances (D16/D39):** `same_day_spread_95p` and "
        "`one_week_drift_max` are published once the calibration runs complete — see "
        "RUNBOOK.md for the procedure.\n"
        "- **Hashes, not bodies (D49):** per-sample JSONL carries `raw_response: null` "
        "in committed artifacts. Use `--keep-raw-responses` for local debug only.\n"
        "- **Live document:** this URL always reflects the latest tag. External links "
        "citing a specific version should pin by `git tag` (see Historical versions below)."
    )


def _historical_versions() -> str:
    return (
        "### Historical versions\n\n"
        "Each published version is an immutable git tag. To cite a specific version in "
        "blog posts or external links, use `https://github.com/<org>/AgentArmor/blob/<tag>/"
        "BENCHMARKS_HEAD_TO_HEAD.md`.\n\n"
        "_(History table populated by `scripts/publish_head_to_head.sh` on each release.)_"
    )


def _draft_banner_if_needed(cells: List[Dict[str, Any]]) -> Optional[str]:
    """Emit a draft banner when the run covered only mock / infra baselines.

    A reader who follows the README link from an in-progress state otherwise
    sees empty tables with no explanation. This renders a one-paragraph
    "DRAFT" notice until real vendor baselines are present.
    """
    real = {"llamaguard", "openai_moderation", "perspective"}
    baselines = {c.get("baseline", "") for c in cells}
    if baselines & real:
        return None
    return (
        "> **DRAFT — infrastructure preview.** This document is regenerated "
        "automatically from the most recent run. The current run exercised only "
        "the mock baseline (CI fixture); real LlamaGuard / OpenAI Moderation / "
        "Perspective numbers land after the first empirical-calibration cycle "
        "(see [`RUNBOOK.md`](RUNBOOK.md) procedures 0 and 5). Tables below "
        "show the schema a reader should expect; entries are `—` until "
        "populated."
    )


def generate_markdown(summary: Dict[str, Any]) -> str:
    """Render the full markdown document from a summary JSON dict."""
    version = summary.get("agentarmor_version", "unknown")
    run_date = summary.get("run_date", "unknown")
    cells = summary.get("cells", [])

    draft_banner = _draft_banner_if_needed(cells)

    parts = [
        GENERATED_MARKER,
        "",
        "# AgentArmor — Head-to-head Comparison",
        "",
        f"**Results as of: AgentArmor v{version}, run {run_date}**",
        "",
    ]
    if draft_banner is not None:
        parts.extend([draft_banner, ""])
    parts.extend([
        _headline_block(),
        "",
        _delta_strip(cells),
        "",
        _operating_point_legend(cells),
        "",
        "## Per-dataset detail",
        "",
        _per_dataset_tables(cells),
        "## Appendices",
        "",
        _pr_curves_appendix(),
        "",
        _does_not_apply_appendix(),
        "",
        _methodology_footer(),
        "",
        _historical_versions(),
        "",
    ])
    return "\n".join(parts)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Generate BENCHMARKS_HEAD_TO_HEAD.md from summary JSON")
    parser.add_argument("--summary", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)

    summary = load_summary(args.summary)
    markdown = generate_markdown(summary)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(markdown)
    print(f"[generate] wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
